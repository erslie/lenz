const std = @import("std");
const pci = @import("pci.zig");

pub const width = 640;
pub const height = 480;

const INDEX_ID = 0x0;
const INDEX_XRES = 0x1;
const INDEX_YRES = 0x2;
const INDEX_BPP = 0x3;
const INDEX_ENABLE = 0x4;
const ENABLED: u16 = 0x01;
const LFB_ENABLED: u16 = 0x40;

var regs: usize = 0;
var fb: [*]volatile u32 = undefined;
pub var ready = false;

fn vbe(index: u16) *volatile u16 {
    return @ptrFromInt(regs + 0x500 + @as(usize, index) * 2);
}

// Find the display device and set it to 640x480, 32-bit color. false if not found
pub fn init() bool {
    const d = pci.find(0x1234, 0x1111) orelse return false;
    if (d.bars[0].kind == .none or d.bars[2].kind == .none) return false;
    regs = d.bars[2].addr;
    fb = @ptrFromInt(d.bars[0].addr);
    const id = vbe(INDEX_ID).*;
    std.log.scoped(.display).info("bochs-display: ID=0x{x} framebuffer 0x{x} ({d} KiB)", .{ id, d.bars[0].addr, d.bars[0].size / 1024 });
    vbe(INDEX_ENABLE).* = 0;
    vbe(INDEX_XRES).* = width;
    vbe(INDEX_YRES).* = height;
    vbe(INDEX_BPP).* = 32;
    vbe(INDEX_ENABLE).* = ENABLED | LFB_ENABLED;
    ready = true;
    fill(0, 0, width, height, 0x000000);
    return true;
}

pub fn pixel(x: usize, y: usize, color: u32) void {
    if (x < width and y < height) fb[y * width + x] = color;
}

pub fn fill(x: usize, y: usize, w: usize, h: usize, color: u32) void {
    var yy = y;
    while (yy < @min(y + h, height)) : (yy += 1) {
        var xx = x;
        while (xx < @min(x + w, width)) : (xx += 1) fb[yy * width + xx] = color;
    }
}

const Glyph = [7]u5;

fn g(comptime rows: [7]*const [5]u8) Glyph {
    var out: Glyph = undefined;
    for (rows, 0..) |r, i| {
        var bits: u5 = 0;
        for (r, 0..) |c, j| {
            if (c == '#') bits |= @as(u5, 1) << @intCast(4 - j);
        }
        out[i] = bits;
    }
    return out;
}

