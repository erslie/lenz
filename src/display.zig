pub fn charW(scale: usize) usize {
    return 6 * scale;
}

pub fn text(x: usize, y: usize, s: []const u8, color: u32, scale: usize) void {
    var cx = x;
    for (s) |c| {
        const gl = font[if (c < 128) c else '?'];
        for (gl, 0..) |row, ry| {
            for (0..5) |rx| {
                if (row & (@as(u5, 1) << @intCast(4 - rx)) != 0)
                    fill(cx + rx * scale, y + ry * scale, scale, scale, color);
            }
        }
        cx += charW(scale);
    }
}

pub fn print(x: usize, y: usize, color: u32, scale: usize, comptime fmt: []const u8, args: anytype) void {
    var buf: [96]u8 = undefined;
    const s = std.fmt.bufPrint(&buf, fmt, args) catch buf[0..];
    text(x, y, s, color, scale);
}
